#!/usr/bin/env python3
"""Check the built source against the pinned release archive plus one exact patch.

This compares file contents and symlink targets, not archive owner/mode metadata:
the latter intentionally changes when an ordinary user extracts the release tar.
"""

from __future__ import annotations

import hashlib
import os
from pathlib import Path, PurePosixPath
import shutil
import subprocess
import sys
import tarfile
import tempfile


ROOT = Path(__file__).resolve().parents[3]
TOOLS = ROOT / "tools/versioning-engine-backend/production"
BUILD_ROOT = ROOT / "target/versioning-engine-backend/production"
ARCHIVE = BUILD_ROOT / "qtwebengine-everywhere-src-6.11.2.tar.xz"
SOURCE = BUILD_ROOT / "source"
PATCH = TOOLS / "qt-6.11.2-owner-abi.patch"
ARCHIVE_ROOT = "qtwebengine-everywhere-src-6.11.2"
ARCHIVE_SHA256 = "6101c1aa00ff933d1b65ee5d167f76e8d71b9ac5b378b0111277723ebda7c163"
PATCH_SHA256 = "7b692e9af2c8eb015c9ca36839b6ef061d95675cd409cea68482ad67d1c7ddb3"
PATCHED = {
    "src/webenginequick/api/qquickwebengineview.cpp",
    "src/webenginequick/api/qquickwebengineview_p.h",
    "src/webenginequick/api/qquickwebengineview_p_p.h",
}


def digest(stream: object) -> str:
    hasher = hashlib.sha256()
    while chunk := stream.read(1024 * 1024):
        hasher.update(chunk)
    return hasher.hexdigest()


def fail(message: str) -> None:
    raise RuntimeError(message)


def main() -> None:
    if not ARCHIVE.is_file() or not SOURCE.is_dir() or not PATCH.is_file():
        fail("pinned archive, extracted source or patch is absent")
    with ARCHIVE.open("rb") as archive_bytes, PATCH.open("rb") as patch_bytes:
        if digest(archive_bytes) != ARCHIVE_SHA256 or digest(patch_bytes) != PATCH_SHA256:
            fail("pinned source archive or patch checksum changed")
    checked = 0
    patched_seen: set[str] = set()
    declared: set[str] = set()
    with tempfile.TemporaryDirectory(prefix="ferric-owner-source-") as temp_name:
        expected = Path(temp_name)
        with tarfile.open(ARCHIVE, "r|xz") as archive:
            for member in archive:
                parts = PurePosixPath(member.name).parts
                if not parts or parts[0] != ARCHIVE_ROOT or ".." in parts:
                    fail(f"unexpected archive path: {member.name}")
                if len(parts) == 1:
                    continue
                relative = Path(*parts[1:])
                relative_name = relative.as_posix()
                declared.add(relative_name)
                current = SOURCE / relative
                if member.isdir():
                    if not current.is_dir() or current.is_symlink():
                        fail(f"source directory differs: {relative_name}")
                    continue
                if member.isfile():
                    archived = archive.extractfile(member)
                    if archived is None:
                        fail(f"cannot read archive member: {relative_name}")
                    with archived:
                        if relative_name in PATCHED:
                            target = expected / relative
                            target.parent.mkdir(parents=True, exist_ok=True)
                            with target.open("wb") as output:
                                shutil.copyfileobj(archived, output)
                            patched_seen.add(relative_name)
                        else:
                            if not current.is_file() or current.is_symlink():
                                fail(f"source file differs: {relative_name}")
                            with current.open("rb") as actual:
                                if digest(archived) != digest(actual):
                                    fail(f"source content differs: {relative_name}")
                    checked += 1
                    continue
                if member.issym():
                    if not current.is_symlink() or os.readlink(current) != member.linkname:
                        fail(f"source symlink differs: {relative_name}")
                    checked += 1
                    continue
                if member.islnk():
                    # The Qt archive does not currently use hard links, so a
                    # new one changes this verification contract explicitly.
                    fail(f"unexpected hard link in archive: {relative_name}")
                fail(f"unexpected archive member type: {relative_name}")

        for directory, subdirectories, filenames in os.walk(SOURCE):
            for name in subdirectories + filenames:
                candidate = Path(directory) / name
                relative = candidate.relative_to(SOURCE)
                if relative.as_posix() in declared:
                    continue
                # Python bytecode is generated by Qt's build helpers, not an
                # input source member. No other unarchived path is accepted.
                if "__pycache__" in relative.parts and candidate.suffix == ".pyc":
                    continue
                if candidate.is_dir() and name == "__pycache__":
                    continue
                fail(f"unarchived source-tree path: {relative.as_posix()}")

        if patched_seen != PATCHED:
            fail(f"missing patched archive files: {sorted(PATCHED - patched_seen)}")
        subprocess.run(
            ["patch", "-d", str(expected), "-p1", "--fuzz=0", "--batch", "-i", str(PATCH)],
            check=True,
            stdout=subprocess.DEVNULL,
        )
        for relative_name in sorted(PATCHED):
            current = SOURCE / relative_name
            if not current.is_file() or current.is_symlink():
                fail(f"patched source file differs: {relative_name}")
            with (expected / relative_name).open("rb") as wanted, current.open("rb") as actual:
                if digest(wanted) != digest(actual):
                    fail(f"patched source content differs: {relative_name}")
    print(f"Verified {checked} release source members and all three exact patched files.")


if __name__ == "__main__":
    try:
        main()
    except (OSError, RuntimeError, subprocess.CalledProcessError, tarfile.TarError) as error:
        print(f"owner-ABI source verification refused: {error}", file=sys.stderr)
        sys.exit(1)
